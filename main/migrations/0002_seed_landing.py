def seed(apps, schema_editor):
    ContentBlock = apps.get_model('main', 'ContentBlock')
    for item in BLOCKS:
        ContentBlock.objects.get_or_create(
            code=item['code'],
            defaults={
                'title': item.get('title', ''),
                'subtitle': item.get('subtitle', ''),
                'body': item.get('body', ''),
                'order': item.get('order', 0),
                'is_visible': item.get('is_visible', True),
            },
        )

    ParticipationStep = apps.get_model('main', 'ParticipationStep')
    for step in STEPS:
        ParticipationStep.objects.get_or_create(
            number=step['number'],
            defaults={'title': step['title'], 'text': step['text']},
        )

    FAQModel = apps.get_model('main', 'FAQ')
    for order, (question, answer) in enumerate(FAQ, start=1):
        FAQModel.objects.get_or_create(
            question=question,
            defaults={'answer': answer, 'order': order},
        )

    # Синглтоны — чтобы менеджер увидел их в админке заполненными значениями
    # по умолчанию (реквизиты Организатора заполняются вручную до старта).
    apps.get_model('main', 'CompanyInfo').objects.get_or_create(id=1)
    apps.get_model('main', 'SEOSettings').objects.get_or_create(id=1)


def unseed(apps, schema_editor):
    apps.get_model('main', 'ContentBlock').objects.filter(
        code__in=[item['code'] for item in BLOCKS],
    ).delete()
    apps.get_model('main', 'ParticipationStep').objects.filter(
        number__in=[step['number'] for step in STEPS],
    ).delete()
    apps.get_model('main', 'FAQ').objects.filter(
        question__in=[question for question, _ in FAQ],
    ).delete()


